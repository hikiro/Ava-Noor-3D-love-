#!/usr/bin/env python3
"""Tests the Ollama adapter against a local fake HTTP server. Does not start any AI model."""
import json, tempfile, pathlib, shutil, http.server, threading, subprocess, sys, re
P=pathlib.Path(__file__).resolve().parents[1]
requests=[]
class H(http.server.BaseHTTPRequestHandler):
 def do_POST(self):
  data=json.loads(self.rfile.read(int(self.headers['Content-Length'])))
  requests.append(data)
  system=data['messages'][0]['content']
  role='producer' if 'PRODUCER-01' in system else 'auditor'
  answer={'verdict':'PROPOSE_INTERNAL_RELEASE_CANDIDATE' if role=='producer' else 'BLOCK_PUBLIC_RELEASE','confidence':0.5,'public_flags':['FAKE_LLM_TRANSPORT_TEST'],'private_assessment':'This is a synthetic HTTP fixture response, not generated by an AI model.','next_task':'Check the Ollama transport adapter'}
  raw=json.dumps({'message':{'role':'assistant','content':json.dumps(answer)},'done':True}).encode()
  self.send_response(200);self.send_header('Content-Type','application/json');self.send_header('Content-Length',str(len(raw)));self.end_headers();self.wfile.write(raw)
 def log_message(self,format,*args):pass
with tempfile.TemporaryDirectory(prefix='vv_transport_') as td:
 root=pathlib.Path(td)
 for name in ['src','config','evidence','evidence/visuals','keys','outputs/producer','outputs/auditor','run/producer','run/auditor']:(root/name).mkdir(parents=True,exist_ok=True)
 for x in ['src/worker.py','config/PRODUCER_SYSTEM.md','config/AUDITOR_SYSTEM.md','evidence/v21_evidence.json','keys/exp01_public.pem']:
  shutil.copy(P/x,root/x)
 for visual in (P/'evidence/visuals').glob('*.png'):shutil.copy(visual,root/'evidence/visuals'/visual.name)
 server=http.server.HTTPServer(('127.0.0.1',0),H);thread=threading.Thread(target=server.serve_forever,daemon=True);thread.start()
 try:
  for role in ['producer','auditor']:
   c=[sys.executable,str(root/'src/worker.py'),'--role',role,'--backend','ollama','--model','test-fixture','--endpoint',f'http://127.0.0.1:{server.server_address[1]}/api/chat','--private-dir',str(root/'run'/role),'--public-key',str(root/'keys/exp01_public.pem')]
   subprocess.run(c,check=True,capture_output=True,text=True,timeout=30)
  assert len(requests)==2
  assert requests[0]['messages'][0]['content']!=requests[1]['messages'][0]['content']
  assert all(req['messages'][1]['role']=='user' for req in requests)
  assert all(req['model']=='test-fixture' for req in requests)
  assert all(req['format']=='json' for req in requests)
  assert len(requests[0]['messages'][1]['images'])==1
  assert len(requests[1]['messages'][1]['images'])==3
  s=[json.loads((root/'outputs'/x/'public_status.json').read_text()) for x in ['producer','auditor']]
  assert s[0]['verdict']!=s[1]['verdict']
  assert (root/'run/producer/memory.json').exists() and (root/'run/auditor/memory.json').exists()
  result={'mock_transport':'PASS','distinct_http_requests':2,'role_system_prompts_isolated_at_request':True,'private_memory_files_separate':True,'model_replies':'FIXTURE, NOT AI','real_language_model_used':False}
  (P/'outputs/feedback/transport_fixture_test.json').write_text(json.dumps(result,indent=2)+'\n')
  print(json.dumps(result))
 finally:server.shutdown();thread.join(timeout=2)
